"""The release workflow's supply-chain contract (S22, REQ-TRUST-002/003).

A release run must produce verifiable artifacts — SBOM, cosign-signed image,
SLSA-style provenance — and `pip-audit` must block a tagged release. The workflow is
the evidence chain, so its shape is pinned here like the credentials gate pins CI:
a step that silently disappears is a release property that silently disappears.
"""

from __future__ import annotations

from pathlib import Path

import pytest
import yaml

RELEASE = Path(__file__).resolve().parents[2] / ".github" / "workflows" / "release.yml"
CI = Path(__file__).resolve().parents[2] / ".github" / "workflows" / "ci.yml"


@pytest.fixture
def release() -> dict:
    return yaml.safe_load(RELEASE.read_text(encoding="utf-8"))


@pytest.fixture
def ci() -> dict:
    return yaml.safe_load(CI.read_text(encoding="utf-8"))


def _steps(job: dict) -> list[dict]:
    return job["steps"]


def _step_text(job: dict) -> str:
    import json

    return json.dumps(_steps(job))


def test_the_release_runs_on_version_tags(release: dict) -> None:
    # YAML parses a bare `on:` as boolean True; the trigger is the tags filter.
    on = release[True]
    assert "push" in on and on["push"]["tags"] == ["v*"]


def test_the_release_has_the_oidc_and_write_permissions(release: dict) -> None:
    """Keyless cosign and provenance need id-token; the release needs packages."""
    jobs = release["jobs"]
    image = jobs["image"]
    assert image["permissions"]["id-token"] == "write"
    assert image["permissions"]["packages"] == "write"
    assert image["permissions"]["contents"] == "write"
    assert image["permissions"]["attestations"] == "write"


def test_the_sbom_is_generated_by_the_shipped_tool(release: dict) -> None:
    """The SBOM is a product artifact: generated by `arachne.tools.sbom`, not ad hoc."""
    text = _step_text(release["jobs"]["sbom"])
    assert "python -m arachne.tools.sbom" in text
    assert "sbom.cdx.json" in text


def test_the_image_is_signed_with_cosign_and_attested(release: dict) -> None:
    text = _step_text(release["jobs"]["image"])
    assert "cosign-installer" in text, "cosign is installed by the pinned installer"
    assert "cosign sign --yes" in text, "the image digest is signed (keyless)"
    assert "cosign attest" in text, "the SBOM is attested to the image digest"
    assert "cyclonedx" in text, "the attestation is typed as a CycloneDX SBOM"
    assert "cosign verify" in text, "the workflow verifies its own signature round-trips"
    # Keyless identity is pinned to this repository's OIDC claim.
    assert "--certificate-oidc-issuer" in text
    assert "--certificate-identity-regexp" in text


def test_provenance_is_generated(release: dict) -> None:
    """SLSA-style provenance: GitHub's official build-provenance attestation."""
    text = _step_text(release["jobs"]["image"])
    assert "actions/attest-build-provenance" in text
    assert "subject-digest" in text


def test_the_sbom_is_schema_validated_in_the_release(release: dict) -> None:
    """REQ-TRUST-011: the shipped tool proves the SBOM passes the CycloneDX schema."""
    text = _step_text(release["jobs"]["sbom"])
    assert "--validate" in text, "the generated SBOM is validated before upload"
    assert "--check sbom.cdx.json" in text, "the written artefact is re-checked"


def test_the_slsa_provenance_is_verified_with_published_tooling(release: dict) -> None:
    """REQ-TRUST-011: the L3 attestation round-trips through cosign verification."""
    text = _step_text(release["jobs"]["image"])
    assert "cosign verify-attestation" in text
    assert "--type slsaprovenance1" in text
    assert "--certificate-oidc-issuer" in text
    assert "--certificate-identity-regexp" in text


def test_pip_audit_blocks_the_release(release: dict) -> None:
    """REQ-TRUST-003: no continue-on-error anywhere in the release audit job."""
    audit = release["jobs"]["audit"]
    steps_text = _step_text(audit)
    assert "pip-audit --strict" in steps_text
    assert audit.get("continue-on-error") is None or audit.get("continue-on-error") is False
    for step in _steps(audit):
        assert step.get("continue-on-error") is not True
    # And the audit job gates the artifact jobs.
    assert release["jobs"]["sbom"]["needs"] == "audit"
    assert release["jobs"]["image"]["needs"] == "sbom"


def test_tool_versions_are_pinned(release: dict) -> None:
    """REQ-TRUST-003: cosign via an env pin; every action via a major-version tag."""
    assert release["env"]["COSIGN_VERSION"].startswith("v")
    text = RELEASE.read_text(encoding="utf-8")
    for action in (
        "actions/checkout@v",
        "actions/setup-python@v",
        "actions/upload-artifact@v",
        "actions/download-artifact@v",
        "actions/attest-build-provenance@v",
        "sigstore/cosign-installer@v",
        "docker/login-action@v",
    ):
        assert action in text, action


def test_ci_is_advisory_off_branches_and_blocking_on_tags(ci: dict) -> None:
    """The promotion in CI's own job: advisory by default, blocking on a tag."""
    deps = ci["jobs"]["dependencies"]
    assert deps["continue-on-error"] == "${{ !startsWith(github.ref, 'refs/tags/') }}"


def test_the_release_workflow_is_not_deployed_so_carries_no_gate_exemption() -> None:
    """The credentials gate treats release.yml as a CI file (generated values)."""
    from arachne.tools.credentials_gate import CI_FILES

    assert ".github/workflows/ci.yml" in CI_FILES
    assert ".github/workflows/release.yml" in CI_FILES
