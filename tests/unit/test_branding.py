"""White-label report branding: validation, merging and the rendered output (S14)."""

from __future__ import annotations

import pytest
from pydantic import ValidationError

from arachne.core.config import ReportSettings, Settings
from arachne.report import (
    Branding,
    BrandingError,
    branding_from_dict,
    branding_from_settings,
    load_branding,
    merge_branding,
)
from arachne.report.html_render import render_html
from arachne.report.markdown import render_markdown
from arachne.report.model import ReportData


def test_the_default_branding_is_neutral() -> None:
    brand = Branding()
    assert brand.product_name == "ARACHNE"
    assert brand.is_customised() is False
    assert brand.display_name() == "ARACHNE"


def test_a_bad_colour_is_refused() -> None:
    with pytest.raises(ValidationError):
        Branding(primary_color="blue")


@pytest.mark.parametrize("url", ["javascript:alert(1)", "ftp://x/logo.png", "logo.png"])
def test_a_non_http_logo_is_refused(url: str) -> None:
    with pytest.raises(ValidationError):
        Branding(logo_url=url)


def test_a_data_uri_and_https_logo_are_accepted() -> None:
    Branding(logo_url="https://mssp.example/logo.png")
    Branding(logo_url="data:image/png;base64,AAAA")


def test_a_project_branding_dict_is_validated() -> None:
    brand = branding_from_dict({"company_name": "Acme Security", "classification": "CONFIDENTIAL"})
    assert brand.company_name == "Acme Security"
    assert brand.is_customised() is True
    with pytest.raises(BrandingError, match="invalid branding"):
        branding_from_dict({"primary_color": "not-a-colour"})


def test_a_nested_branding_block_is_accepted() -> None:
    brand = branding_from_dict({"branding": {"company_name": "Nested Co"}})
    assert brand.company_name == "Nested Co"


def test_load_branding_from_yaml_and_json(tmp_path: object) -> None:
    from pathlib import Path

    directory = Path(str(tmp_path))
    yaml_path = directory / "brand.yaml"
    yaml_path.write_text("company_name: Acme\nprimary_color: '#112233'\n")
    assert load_branding(yaml_path).company_name == "Acme"
    json_path = directory / "brand.json"
    json_path.write_text('{"company_name": "JsonCo"}')
    assert load_branding(json_path).company_name == "JsonCo"
    with pytest.raises(BrandingError, match="does not exist"):
        load_branding(directory / "missing.yaml")


def test_merge_gives_the_override_only_its_non_default_fields() -> None:
    base = Branding(company_name="Platform", classification="INTERNAL", footer_text="base footer")
    override = Branding(company_name="Acme", primary_color="#00aa00")
    merged = merge_branding(base, override)
    assert merged.company_name == "Acme"
    assert merged.primary_color == "#00aa00"
    # Untouched by the override, so the deployment default survives.
    assert merged.classification == "INTERNAL"
    assert merged.footer_text == "base footer"


def test_merge_with_no_override_returns_the_base() -> None:
    base = Branding(company_name="Platform")
    assert merge_branding(base, None) == base
    assert merge_branding(base, Branding()) == base


def test_settings_resolve_the_branding_file(tmp_path: object) -> None:
    from pathlib import Path

    path = Path(str(tmp_path)) / "brand.yaml"
    path.write_text("company_name: Acme\n")
    settings = Settings(report=ReportSettings(branding_path=str(path)))
    assert branding_from_settings(settings).company_name == "Acme"
    assert branding_from_settings(None).is_customised() is False


# --------------------------------------------------------------------------- rendering
def _branded(report: object, **branding: object) -> object:
    return report.model_copy(update={"branding": Branding(**branding)})  # type: ignore[attr-defined]


def test_markdown_carries_company_classification_and_footer(synthetic_report: object) -> None:
    report = _branded(
        synthetic_report,
        company_name="Acme Security",
        tagline="Managed detection",
        classification="CONFIDENTIAL",
        contact="soc@acme.example",
        footer_text="Prepared for Acme Corp",
        show_arachne_branding=False,
    )
    text = render_markdown(report)  # type: ignore[arg-type]
    assert text.startswith("**CONFIDENTIAL**")
    assert "*Acme Security · Managed detection*" in text
    assert "Prepared for Acme Corp" in text
    assert "soc@acme.example" in text
    assert "*Acme Security.*" in text


def test_markdown_for_the_default_branding_is_unchanged(synthetic_report: object) -> None:
    text = render_markdown(synthetic_report)  # type: ignore[arg-type]
    assert not text.startswith("**")
    assert "Generated by" not in text
    assert "ARACHNE 0.1.0" in text or "ARACHNE" in text


def test_html_carries_the_logo_colours_and_banner(synthetic_report: object) -> None:
    report = _branded(
        synthetic_report,
        company_name="Acme Security",
        logo_url="https://acme.example/logo.png",
        primary_color="#112233",
        accent_color="#aa0000",
        classification="CONFIDENTIAL",
        footer_text="Prepared for Acme",
    )
    document = render_html(report)  # type: ignore[arg-type]
    assert 'class="classification">CONFIDENTIAL' in document
    assert 'src="https://acme.example/logo.png"' in document
    assert "--brand:#112233" in document
    assert "--accent:#aa0000" in document
    assert "Prepared for Acme" in document


def test_html_logo_text_is_used_when_no_url_is_set(synthetic_report: object) -> None:
    report = _branded(synthetic_report, company_name="Acme", logo_text="AC")
    assert 'class="logo-mark">AC' in render_html(report)  # type: ignore[arg-type]


def test_the_json_document_contains_the_branding(synthetic_report: object) -> None:
    from arachne.report.json_render import report_payload

    payload = report_payload(synthetic_report)  # type: ignore[arg-type]
    assert payload["branding"]["product_name"] == "ARACHNE"


def test_the_default_html_has_no_branding_markup(synthetic_report: object) -> None:
    document = render_html(synthetic_report)  # type: ignore[arg-type]
    assert 'class="brand"' not in document
    assert "classification" not in document


def test_report_data_rejects_unknown_branding_fields(synthetic_report: object) -> None:
    with pytest.raises(ValidationError):
        ReportData(**{**synthetic_report.model_dump(), "branding": {"nope": 1}})  # type: ignore[attr-defined]
