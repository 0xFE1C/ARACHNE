#: Statement heads a generated payload may never contain (REQ-FUZZ-001, via REQ-PROOF-008).
#: Reused, not re-declared: a fuzzed string is a payload like any other, and two tables that
#: could drift apart would be one table too many. ``UPDATE``/``INSERT`` are absent here for
#: the same reason they are in the proof ladder — they are not destructive by *shape* — but a
#: fuzz case never builds one on purpose, so in practice the SQL surface a fuzzer may
#: synthesize is read-only queries and syntax fragments.
DESTRUCTIVE_SQL_HEADS: Final[frozenset[str]] = PROHIBITED_SQL_HEADS

#: Byte sequences a generated payload may never contain, grouped by the class of harm.
#: Matched case-sensitively against the payload's lowercased printable runs (see
#: :func:`_text_tokens`), never against raw binary bytes: "did this message contain the word
#: shutdown" is a question about the message's text, and a TLS key share must not be able to
#: answer it by coincidence.
#:
#: Note what is *not* here. Path traversal (`../`), a NUL byte, a quote, an angle bracket and
#: an over-long form field are all legitimate fuzzing material — each is a finding this
#: program exists to produce — so the table names only payloads whose *purpose* is harm rather
#: than payloads that look alarming.
FORBIDDEN_SEQUENCES: Final[Mapping[str, tuple[bytes, ...]]] = {
    "sql": (
        # Lowercased: the table is matched against the payload's lowercased text, so encoding a
        # head as it is spelled (``ALTER``) would never match the word it names.
        *(head.lower().encode("ascii") for head in sorted(DESTRUCTIVE_SQL_HEADS)),
        b"drop database",
        b"drop table",
        b"delete from",
        b"truncate table",
    ),
    "shell": (
        b"$(",
        b"`",
        b";rm ",
        b"&&",
        b"||/",
        b"/bin/sh",
        b"/bin/bash",
        b"/dev/tcp",
        b"nc -e",
        b"ncat -e",
        b"mkfifo",
    ),
    "destructive-command": (
        b"rm -rf",
        b"rm -fr",
        b"shred ",
        b"wipefs",
        b"mkfs",
        b"dd if=",
        b":(){",
        b"chmod 777 /",
        b"chown -r",
    ),
    "remaining-infrastructure": (
        b"shutdown",
        b"reboot",
        b"poweroff",
        b"halt -",
        b"init 0",
        b"init 6",
        b"format c:",
        b"factory reset",
        b"factoryreset",
        b"clear config",
    ),
}

#: Table/identity markers a generated payload may never name (REQ-PROOF-011
#: "credential/account mutation"): a fuzzer has no business synthesizing a credential,
#: session or permission-store reference. A multi-word marker is matched as a substring of
#: the payload's text; a single-token marker is matched against the payload's words, so
#: ``passwd`` fires on ``passwd`` and not on ``passwd_file_id``.
CREDENTIAL_MUTATION_MARKERS: Final[frozenset[bytes]] = frozenset(
    {
        b"grant ",
        b"revoke ",
        b"alter user",
        b"create user",
        b"drop user",
        b"set password",
        b"password_modify",
        b"passwdmodify",
        b"chpasswd",
        b"adduser",
        b"useradd",
        b"chown root",
    }
)

#: The fraction of a payload that must be printable-or-whitespace before the *textual* classes
#: are applied to it. Below this the payload is treated as binary, and the only prohibition that
#: applies is the operation table — which is enforced structurally at the grammar rather than by
#: reading bytes. The reason is precision, not leniency: "did this message contain the word
#: shutdown" is not a meaningful question about a TLS ClientHello's key share, and asking it of
#: one produces refusals on cases that are not remotely dangerous (a 32-byte nonce can spell
#: anything, one time in a few thousand).
_TEXTUAL_FRACTION: Final = 0.5

#: The operations each protocol's fuzz grammars may carry, keyed by the protocol names
#: :mod:`arachne.fuzz.wire` uses. Anything absent is unavailable to a grammar.
READ_ONLY_OPERATIONS: Final[Mapping[str, frozenset[int]]] = {
    # Modbus public function codes: read coils/discrete inputs/holding/input registers,
    # read exception status, report server id, read device identification. The write family
    # (0x05/0x06/0x0F/0x10), the diagnostics family (0x08) and read/write-multiple (0x17)
    # are excluded.
    "modbus": frozenset({0x01, 0x02, 0x03, 0x04, 0x07, 0x11, 0x2B}),
    # DNP3 link functions: TEST_LINK_STATES(2) and REQUEST_LINK_STATUS(9) only.
    # RESET_LINK_STATES(0)/RESET_USER_PROCESS(1) are not read-only, and neither is any
    # application function code — READ(1) is read-only in name only, since a DNP3 READ on a
    # control point is how a SELECT/OPERATE exchange begins. So a fuzz grammar gets the link
    # layer and nothing else.
    "dnp3": frozenset({0x02, 0x09}),
    # SNMP PDUs, by their BER tag: GetRequest(0xA0), GetNextRequest(0xA1),
    # GetBulkRequest(0xA5). SetRequest(0xA3) writes, and the trap/inform tags are outbound.
    "snmp": frozenset({0xA0, 0xA1, 0xA5}),
    # S7comm jobs: Read Var(0x04), Start Upload(0x1D), Upload(0x1E), and the Setup
    # Communication(0xF0) handshake every connection opens with. Write Var(0x05), the
    # download family and PLC stop(0x28)/control(0x29) are excluded.
    "s7comm": frozenset({0x04, 0x1D, 0x1E, 0xF0}),
    # BACnet confirmed services: ReadProperty(12), ReadPropertyMultiple(14).
    # WriteProperty(15), WritePropertyMultiple(16), DeviceCommunicationControl(17) excluded.
    "bacnet": frozenset({12, 14}),
    # LDAP request tags: bind(0x60), search(0x63), compare(0x6E), abandon(0x50).
    # modify(0x66), add(0x68), delete(0x4A), modifyDN(0x6C) and extended(0x77, which carries
    # passwdModify) are excluded.
    "ldap": frozenset({0x50, 0x60, 0x63, 0x6E}),
}

#: Read-only *verbs* for text protocols, where the operation is a word rather than a code.
#: ``SET``/``DEL``/``FLUSHALL``/``CONFIG``/``SCRIPT``/``EVAL``/``SHUTDOWN`` are excluded by
#: omission, which is the fail-closed direction.
READ_ONLY_VERBS: Final[Mapping[str, frozenset[str]]] = {
    "redis": frozenset({"PING", "ECHO", "INFO", "DBSIZE", "TYPE", "TTL", "GET", "EXISTS"}),
    "memcached": frozenset({"stats", "get", "version"}),
    "postgres": frozenset({"SELECT"}),
}

#: HTTP methods a fuzzed request may use. ``GET``/``HEAD``/``OPTIONS`` are read-only by
#: definition; ``POST`` is permitted because REQ-FUZZ-003 asks for parameter *and form*
#: fuzzing and a form is a body. Nothing else is: no ``PUT``/``PATCH``/``DELETE`` (a state
#: change on a REST surface), no ``CONNECT``/``TRACE`` (proxy and reflection tricks). What
#: constrains a POST here is the payload table above, exactly as it constrains the M3 checks
#: the fuzz candidates feed.
HTTP_READ_ONLY_METHODS: Final[frozenset[str]] = frozenset({"GET", "HEAD", "OPTIONS", "POST"})

#: Protocols with an operation code or verb a grammar can declare.
OPERATION_PROTOCOLS: Final[frozenset[str]] = frozenset(READ_ONLY_OPERATIONS) | frozenset(
    READ_ONLY_VERBS
)


@dataclass(frozen=True, slots=True)
class NonDestructiveVerdict:
    """The prohibition table's reading of one generated payload."""

    problems: tuple[str, ...] = ()
    classes: tuple[str, ...] = ()

    @property
    def ok(self) -> bool:
        return not self.problems

    def to_dict(self) -> dict[str, Any]:
        return {"ok": self.ok, "problems": list(self.problems), "classes": list(self.classes)}


#: The printable runs of a payload: tab/LF/CR and the ASCII printable range, two characters
#: or more, so a lone byte cannot form a "word".
_ASCII = re.compile(rb"[\x09\x0a\x0d\x20-\x7e]{2,}")
_WORD = re.compile(rb"[a-z0-9_]{3,}")


def _is_textual(payload: bytes) -> bool:
    """True when ``payload`` is predominantly text, so the textual classes are meaningful.

    A binary protocol message is judged by its operation table (structurally, at the grammar),
    not by whether its bytes happen to contain a word — see :data:`_TEXTUAL_FRACTION`.
    """
    if not payload:
        return True
    readable = sum(1 for byte in payload if byte in b"\t\n\r" or 0x20 <= byte <= 0x7E)
    return readable / len(payload) >= _TEXTUAL_FRACTION


def _text_tokens(payload: bytes) -> bytes:
    """The payload's lowercased printable runs, space-joined — what the table matches on."""
    return b" ".join(match.group(0).lower() for match in _ASCII.finditer(payload))


def fuzz_payload_problems(payload: bytes, *, protocol: str | None = None) -> NonDestructiveVerdict:
    """Every reason ``payload`` may not be sent, and the classes they belong to.

    A verdict rather than an exception, because the runner records *why* a case was
    discarded: "the engine produced a prohibited payload" is a fact about the engine worth
    keeping, and it is not the same event as a target refusing the message.

    This is the *payload* half of the table. The operation half is not checked here, and
    deliberately: a scan of a message's raw bytes for an operation code at a fixed offset
    cannot tell an operation from a byte that a length-changing mutation shifted into that
    position, so it refuses legitimate cases (a shortened community string moves an SNMP
    error-status tag into the PDU tag's offset). The operation rule is enforced where it is
    exact instead — the grammar refuses a state-changing operation *at definition time* and
    re-checks every value it is about to write into an operation field
    (:meth:`~arachne.fuzz.grammar.MessageGrammar._replacement`), which is a structural
    guarantee rather than a heuristic one. ``protocol`` is still accepted so the caller's
    intent is on the record and a future exact check can use it.
    """
    if not _is_textual(payload):
        # A predominantly-binary payload carries no statement: what could make it destructive is
        # an operation code, and that is refused at the grammar (REQ-FUZZ-001) rather than
        # guessed at from bytes.
        return NonDestructiveVerdict()
    text = _text_tokens(payload)
    problems: list[str] = []
    classes: list[str] = []
    for name, needles in FORBIDDEN_SEQUENCES.items():
        hits = [needle for needle in needles if needle in text]
        if hits:
            classes.append(name)
            rendered = ", ".join(repr(hit.decode("latin-1")) for hit in hits[:3])
            problems.append(f"{name}: payload contains {rendered}")
    for marker in sorted(CREDENTIAL_MUTATION_MARKERS):
        if b" " in marker or b"_" in marker:
            if marker in text:
                classes.append("credential-mutation")
                problems.append(f"credential-mutation: payload contains {marker.decode()!r}")
        elif marker in {match.group(0) for match in _WORD.finditer(text)}:
            classes.append("credential-mutation")
            problems.append(f"credential-mutation: payload contains {marker.decode()!r}")
    # Evasion/obfuscation is the proof ladder's rule, applied to this payload's text rather
    # than reimplemented here: one table, one implementation, no drift (REQ-PROOF-011).
    try:
        encode_free(text.decode("latin-1"))
    except ProofRefused as exc:
        classes.append("evasion")
        problems.append(f"evasion: {exc.reason}")
    # De-duplicate while keeping first-seen order (a report reads better that way).
    return NonDestructiveVerdict(
        problems=tuple(dict.fromkeys(problems)), classes=tuple(dict.fromkeys(classes))
    )


def require_non_destructive(
    payload: bytes, *, protocol: str | None = None, source: str = "fuzz"
) -> bytes:
    """Return ``payload``, or refuse it with :class:`FuzzPayloadRefused`.

    The refusal happens inside the process and before the egress call, so a prohibited
    payload is never written to a socket.
    """
    verdict = fuzz_payload_problems(payload, protocol=protocol)
    if not verdict.ok:
        msg = f"{source}: generated payload is prohibited ({' ; '.join(verdict.problems)})"
        raise FuzzPayloadRefused(msg, reason="; ".join(verdict.problems))
    return payload


def read_only_operations(protocol: str) -> frozenset[int] | None:
    """The operations ``protocol`` may carry in a fuzz grammar (``None``: no opcode field)."""
    return READ_ONLY_OPERATIONS.get(protocol)


def operation_is_destructive(protocol: str, code: int) -> bool:
    """True when ``code`` is not a declared read-only operation of ``protocol``.

    A protocol with no operation table at all (HTTP, DNS, TLS) reports ``False``: the
    question does not apply, and the payload table is what constrains those. The question is
    answered for every protocol that *does* have one, and there the answer is fail-closed —
    any code outside the allowlist is destructive.
    """
    allowed = READ_ONLY_OPERATIONS.get(protocol)
    if allowed is None:
        return False
    return code not in allowed


def grammar_operation_problems(
    protocol: str, operations: Iterable[int], *, field_name: str = "operation"
) -> tuple[str, ...]:
    """Reasons a grammar may not declare ``operations`` for ``protocol``.

    Called from the grammar constructor, so a message grammar naming a write operation
    cannot be *defined*, let alone used. Empty for a protocol with no operation table.
    """
    allowed = READ_ONLY_OPERATIONS.get(protocol)
    if allowed is None:
        return ()
    return tuple(
        f"{field_name} {code:#x} is not a declared read-only {protocol} operation "
        f"(allowed: {', '.join(f'{item:#x}' for item in sorted(allowed))})"
        for code in operations
        if code not in allowed
    )


def require_read_only_operations(
    protocol: str, operations: Iterable[int], *, field_name: str = "operation"
) -> tuple[int, ...]:
    """Return the declared operations, refusing any that is not read-only."""
    codes = tuple(operations)
    problems = grammar_operation_problems(protocol, codes, field_name=field_name)
    if problems:
        msg = f"fuzz grammar declares a state-changing operation: {'; '.join(problems)}"
        raise FuzzPayloadRefused(msg, reason="; ".join(problems))
    return codes


@dataclass(frozen=True, slots=True)
class ProhibitionSummary:
    """The table as a report renders it — what fuzzing may not generate, in one place."""

    classes: tuple[str, ...] = field(default_factory=lambda: tuple(FORBIDDEN_SEQUENCES))
    protocols: tuple[str, ...] = field(default_factory=lambda: tuple(sorted(READ_ONLY_OPERATIONS)))

    def to_dict(self) -> dict[str, Any]:
        return {
            "classes": list(self.classes),
            "destructive_sql_heads": sorted(DESTRUCTIVE_SQL_HEADS),
            "protocols": {
                name: sorted(codes) for name, codes in sorted(READ_ONLY_OPERATIONS.items())
            },
            "verbs": {name: sorted(verbs) for name, verbs in sorted(READ_ONLY_VERBS.items())},
            "http_methods": sorted(HTTP_READ_ONLY_METHODS),
        }
