"""The prohibition table, applied to fuzzing (S30, area FUZZ, REQ-FUZZ-001).

Fuzzing generates input nobody wrote. That is exactly why area FUZZ needs its own reading of
the prohibition table rather than a copy of the proof ladder's: the proof ladder refuses a
*payload* a human authored, while a fuzzer can synthesize a payload no human would, and the
only way to keep "discovery, never disruption" true is to make the disruptive space
unrepresentable rather than merely absent from a wordlist.

Three enforcement layers, all structural:

**Payload-level.** Every byte string a fuzzing engine is about to send passes
:func:`fuzz_payload_problems`. It refuses the program's long-standing prohibitions —
destructive SQL (reusing the proof ladder's ``PROHIBITED_SQL_HEADS``, not a second copy),
shell metacharacters, destructive commands, remaining-infrastructure verbs, and
credential/account mutation — plus the evasion/obfuscation rule, which is applied by calling
the proof ladder's own ``encode_free`` on the payload's printable text. A fuzzed payload is a
payload: one table, one implementation, no drift.

**Operation-level.** For a protocol whose messages carry an operation code (a Modbus function
code, a DNP3 link function, an SNMP PDU type, an S7 job, a BACnet service, an LDAP request
tag), :data:`READ_ONLY_OPERATIONS` names the operations that are proven not to change target
state. A message grammar declares which operations it may carry, and the grammar constructor
refuses a declaration outside that set — so *no mutation operator can select a write
operation*: the operation field of a fuzzed message is drawn from its declared allowlist, not
from the byte space. That makes "fuzzing can never issue a write" a property of the grammar
rather than of a reviewer's attention, which is what makes it testable.

**Structural.** :func:`grammar_operation_problems` is called from the grammar constructor, so
a state-changing operation cannot be *declared*; :func:`require_non_destructive` runs on the
generated bytes before the egress call, so it cannot be *sent*. There is no code path that
does one without the other.

The tables are deliberately inclusive of operations that are merely questionable: an
operation whose effect this build cannot prove read-only is treated as destructive, because
excluding a read-only opcode from a fuzz grammar costs some coverage, while including a
state-changing one costs a changed target.
"""

from __future__ import annotations

import re
from collections.abc import Iterable, Mapping
from dataclasses import dataclass, field
from typing import Any, Final

from arachne.core.errors import FuzzPayloadRefused
from arachne.core.proof import PROHIBITED_SQL_HEADS, ProofRefused, encode_free

