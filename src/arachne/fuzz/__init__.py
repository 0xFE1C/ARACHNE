"""Bounded safe fuzzing (S30, area FUZZ) — REQ-FUZZ-001...006.

Fuzzing here is an authorized, attested, hard-bounded activity whose goal is **discovery, never
disruption**. The package is written so that the safe behaviour is the only behaviour the code
can express:

* :mod:`arachne.fuzz.attestation` — the area's own grant, on top of the scan's. Non-production
  targets only by default, coverage decided by the same rule the scan attestation uses, and the
  refusal audited before it is raised.
* :mod:`arachne.fuzz.bounds` — the hard ceilings: per-target wall-clock seconds, requests and
  cases, spent *before* each request so a bound is enforced on the intent.
* :mod:`arachne.fuzz.prohibitions` — the prohibition table applied to generated bytes: no
  destructive statement, no state-changing protocol operation, no shell metacharacter, no
  remaining-infrastructure payload, no evasion encoding. Operation fields are confined to a
  declared read-only allowlist, so a fuzz grammar cannot issue a write operation.
* :mod:`arachne.fuzz.grammar` / :mod:`arachne.fuzz.wire` — message grammars over the real M2 wire
  builders, with grammar-aware mutation that keeps a message well-framed and puts the pressure on
  the length, count and boundary values parsers forget to validate.
* :mod:`arachne.fuzz.health` — health probes before and after every batch and inside it, and the
  guard that stops the run at the first degradation signal.
* :mod:`arachne.fuzz.candidates` — **candidates, never findings**. Only the proof ladder reports.
* :mod:`arachne.fuzz.engines` — the pluggable engine seam; the default is grammar-based and adds
  no dependency.
* :mod:`arachne.fuzz.runner` — where the rules above are enforced on the path every case takes:
  authorize, then bound, then send through the *inherited* scoped clients, then judge, then audit.
* :mod:`arachne.fuzz.plan` — the plan document, so what was authorized, targeted and bounded is a
  record an operator can review and diff rather than a shell history line.

The one-line summary: :class:`FuzzRunner` is the only thing that sends anything, and it will not
send anything the other modules have not approved.
"""

