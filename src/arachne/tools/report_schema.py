"""Regenerate the committed report JSON Schema (S26, REQ-ECOS-005).

The report document's schema is the contract of : it is *generated* from
:class:`~arachne.report.model.ReportData` and committed, so a consumer (a DefectDojo
importer, a customer's data warehouse, the SDKs) can validate a document without importing
ARACHNE. Until S26 that file was regenerated by hand, which is exactly the kind of step that
silently rots. This tool is the repeatable form of it, and
``python -m arachne.tools.report_schema --check`` is the drift gate, and CI runs it:
it regenerates in memory and fails the build when the committed file differs.

Usage::

    python -m arachne.tools.report_schema            # write the current version's file
    python -m arachne.tools.report_schema --check    # exit 1 if the committed file drifts
    python -m arachne.tools.report_schema --stdout   # print, do not write

Only the *current* :data:`~arachne.report.model.REPORT_SCHEMA_VERSION` is written; the
earlier ``report-schema-1.<n>.json`` files are frozen history and are never touched.
"""

from __future__ import annotations

import json
import sys
from pathlib import Path
from typing import Any, Final

from arachne.report.model import REPORT_SCHEMA_VERSION, ReportData
from arachne.report.schema_policy import SCHEMA_HISTORY, policy_violations

__all__ = [
    "SCHEMA_RESOURCE",
    "main",
    "render_schema",
    "schema_bytes",
    "schema_document",
    "schema_path",
]

#: Where a written schema lands, relative to ``templates/``.
SCHEMA_RESOURCE: Final[tuple[str, ...]] = ("report", f"report-schema-{REPORT_SCHEMA_VERSION}.json")

#: The dialect the committed schema declares. Pydantic emits a 2020-12-shaped document, and
#: the shipped files have always carried this header, so the generator reproduces it exactly.
SCHEMA_DIALECT: Final = "https://json-schema.org/draft/2020-12/schema"
SCHEMA_ID: Final = f"https://arachne.local/schema/report-{REPORT_SCHEMA_VERSION}.json"


def schema_document() -> dict[str, Any]:
    """The full committed document: pydantic schema, dialect header, ``$id`` and the policy.

    ``$id`` names the schema *version*, so a document can be validated against the schema of
    the revision it claims in ``schema_version`` — which is what makes keeping the older
    ``report-schema-1.<n>.json`` files worth the space.

    WP-21 (REQ-DATA-007): the document also carries its machine-readable changelog and its
    deprecation records, taken from :data:`~arachne.report.schema_policy.SCHEMA_HISTORY`.
    Because the generator emits them, the current file cannot claim a policy the code does not
    declare; because every frozen file carries the same pair, a consumer can read the policy
    from whichever revision it holds.
    """
    schema = ReportData.model_json_schema()
    revision = next(item for item in SCHEMA_HISTORY if item.version == REPORT_SCHEMA_VERSION)
    return {"$schema": SCHEMA_DIALECT, "$id": SCHEMA_ID, **schema, **revision.metadata()}


def render_schema() -> str:
    """The canonical schema text for the current report model.

    ``sort_keys`` and ``indent=2`` make the file a diffable stable artifact; ``ensure_ascii``
    keeps the committed bytes ASCII-only, so the file does not depend on an editor's encoding.
    """
    return json.dumps(schema_document(), indent=2, sort_keys=True) + "\n"


def schema_bytes() -> bytes:
    return render_schema().encode("utf-8")


def schema_path(root: Path | None = None) -> Path:
    """The on-disk path of the current schema.

    ``root`` defaults to the *real* templates directory, resolved from the ``arachne``
    package's own file location rather than ``importlib.resources.files("arachne.templates")``:
    ``templates`` is a namespace package, so ``files()`` returns an ``importlib.resources``
    ``MultiplexedPath`` whose ``str()`` is a repr, not a filesystem path. A writing tool needs a
    path, so it takes the one the package actually lives at.
    """
    if root is not None:
        return Path(root).joinpath(*SCHEMA_RESOURCE)
    import arachne

    base = Path(arachne.__file__).resolve().parent / "templates"
    return base.joinpath(*SCHEMA_RESOURCE)


def main(argv: list[str] | None = None) -> int:
    args = list(sys.argv[1:] if argv is None else argv)
    check = "--check" in args
    to_stdout = "--stdout" in args
    payload = render_schema()
    if to_stdout:
        sys.stdout.write(payload)
        return 0
    target = schema_path()
    if check:
        try:
            existing = target.read_text(encoding="utf-8")
        except OSError as exc:
            sys.stderr.write(f"error: cannot read {target}: {exc}\n")
            return 1
        problems = list(policy_violations())
        if existing != payload:
            problems.insert(
                0,
                f"{target.name} is stale; run `python -m arachne.tools.report_schema`",
            )
        if problems:
            for problem in problems:
                sys.stderr.write(f"error: {problem}\n")
            return 1
        sys.stdout.write(
            f"{target.name} is up to date (schema {REPORT_SCHEMA_VERSION}); "
            f"the schema policy holds\n"
        )
        return 0
    target.write_text(payload, encoding="utf-8")
    sys.stdout.write(f"wrote {target} (schema {REPORT_SCHEMA_VERSION})\n")
    return 0


def _schema_dict() -> dict[str, Any]:  # pragma: no cover - convenience for callers/tests
    return ReportData.model_json_schema()


if __name__ == "__main__":  # pragma: no cover - CLI entry
    raise SystemExit(main())
